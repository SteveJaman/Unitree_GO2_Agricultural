#!/usr/bin/env python3
"""Generate gazebo/worlds/traversability_lab.sdf: a small closed room (7 m x 4 m) with only the
five traversability test objects. Same physics, sensors, light and ground as agri_field.sdf (it
reuses that file's header), so it runs with the same launcher and is much lighter than the field.

  python3 gazebo/worlds/build_lab_world.py
  SIM_WORLD=traversability_lab SIM_SPAWN="-2.8 0 0" SIM_CAMERA=0 ./scripts/runtime/wifi_nav.sh --sim

The dog spawns at (-2.8, 0) facing +x. If the map frame starts at the spawn pose, the objects are
at these (x forward, y left) positions:
  cable   0.8,  0.0   3 cm   no collision (across the path; step over)
  mat     1.8,  0.0   2 cm   no collision (step over)
  toolbox 3.0, +0.9  12 cm   collision    (above the step limit; avoid)
  phone   3.0, -0.9   8 cm   collision    (low but fragile; avoid)
  vase    4.0,  0.0  30 cm   collision    (tall and fragile; avoid)
Objects without collision stand in for stepping over: the sim base only glides.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "agri_field.sdf")
DST = os.path.join(HERE, "traversability_lab.sdf")

X0, X1, Y0, Y1 = -3.5, 3.5, -2.0, 2.0     # room walls
WALL_H, WALL_T = 1.2, 0.1
WALL_RGB = "0.82 0.80 0.76"
CABLE_RGB, MAT_RGB = "0.05 0.05 0.05", "0.15 0.35 0.65"
FRAGILE_RGB, TOOLBOX_RGB = "0.85 0.10 0.10", "0.90 0.75 0.10"


def link(name, x, y, z, sx, sy, sz, rgb, collision=True):
    col = (f'        <collision name="c"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry></collision>\n'
           if collision else "")
    return (f'      <link name="{name}">\n        <pose>{x:.3f} {y:.3f} {z:.3f} 0 0 0</pose>\n{col}'
            f'        <visual name="v"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry>\n'
            f'          <material><ambient>{rgb} 1</ambient><diffuse>{rgb} 1</diffuse></material></visual>\n'
            f'      </link>\n')


def model(name, links):
    return f'    <model name="{name}">\n      <static>true</static>\n{"".join(links)}    </model>\n'


def main():
    src = open(SRC).read()
    cut = '    <model name="walls">'
    if src.count(cut) != 1 or src.count('<world name="agri_field">') != 1:
        sys.exit("ERROR: agri_field.sdf does not have the expected layout (one 'walls' model, one world name).")
    head = src[:src.index(cut)].replace('<world name="agri_field">', '<world name="traversability_lab">')
    head = re.sub(r"<!--.*?-->", "<!--\n  traversability_lab.sdf: GENERATED by build_lab_world.py from agri_field.sdf.\n"
                  "  Do not edit by hand; edit the script and rerun it. A 7 m x 4 m closed room with five\n"
                  "  traversability test objects. @RENDER_ENGINE@ is substituted by start_inside.sh.\n-->",
                  head, count=1, flags=re.S)
    w, lx, ly = WALL_T, X1 - X0 + WALL_T, Y1 - Y0 + WALL_T
    room = model("room", [
        link("south", (X0 + X1) / 2, Y0, WALL_H / 2, lx, w, WALL_H, WALL_RGB),
        link("north", (X0 + X1) / 2, Y1, WALL_H / 2, lx, w, WALL_H, WALL_RGB),
        link("west", X0, (Y0 + Y1) / 2, WALL_H / 2, w, ly, WALL_H, WALL_RGB),
        link("east", X1, (Y0 + Y1) / 2, WALL_H / 2, w, ly, WALL_H, WALL_RGB)])
    objects = model("test_objects", [
        link("cable_1", -2.0, 0.0, 0.015, 0.03, 0.9, 0.03, CABLE_RGB, collision=False),
        link("mat_1", -1.0, 0.0, 0.010, 0.8, 1.0, 0.02, MAT_RGB, collision=False),
        link("toolbox_1", 0.2, 0.9, 0.06, 0.3, 0.5, 0.12, TOOLBOX_RGB),
        link("phone_1", 0.2, -0.9, 0.04, 0.15, 0.08, 0.08, FRAGILE_RGB),
        link("vase_1", 1.2, 0.0, 0.15, 0.12, 0.12, 0.30, FRAGILE_RGB)])
    open(DST, "w").write(head + room + objects + "  </world>\n</sdf>\n")
    print(f"wrote {DST}")


if __name__ == "__main__":
    main()

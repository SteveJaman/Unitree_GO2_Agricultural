#!/usr/bin/env python3
"""
build_nft46_assets.py: meshes and textures for the NFT 4-6 lab world (no downloads).

Writes gazebo/worlds/models/nft46/ (model://nft46/...):
  meshes/tube_<mm>.obj     green slotted square steel tube, 1.25 in, punched holes every
                           inch on all four faces (the rack frame in the lab photos); one
                           mesh per length so the hole pattern is not stretched
  meshes/channel.obj       a 4 ft NFT channel: flat cover with a raised lip along each edge,
                           sides tapering to a narrower bottom, closed ends (white PVC)
  meshes/floor.obj         a 12 x 12 m floor quad with its texture tiled every 0.6 m
  textures/tube.png        green paint with dark round holes and the odd slot
  textures/floor.png       light grey speckled vinyl, as the lab floor
build_cropking_nft46_world.py calls tube_mesh() for the lengths it needs and build().

Usage: python3 build_nft46_assets.py
"""
import math
import os

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "models", "nft46")
IN = 0.0254
TUBE = 1.25 * IN
HOLE_PITCH = 1.0 * IN               # one hole per inch along the tube
CH_LEN, CH_W, CH_H = 48 * IN, 4.0 * IN, 1.75 * IN


def write_obj(name, verts, uvs, normals, faces, mtl, texture=None, kd=(1, 1, 1), ks=0.1, ns=20, ke=None):
    """faces: list of ((v, t, n), ...) 1-based-ready 0-based triples."""
    os.makedirs(os.path.join(OUT, "meshes"), exist_ok=True)
    with open(os.path.join(OUT, "meshes", f"{name}.mtl"), "w", newline="\n") as f:
        f.write(f"newmtl {mtl}\nKa {kd[0]} {kd[1]} {kd[2]}\nKd {kd[0]} {kd[1]} {kd[2]}\nKs {ks} {ks} {ks}\nNs {ns}\n")
        if ke:
            f.write(f"Ke {ke[0]} {ke[1]} {ke[2]}\n")
        if texture:
            f.write(f"map_Kd ../textures/{texture}\n")
    with open(os.path.join(OUT, "meshes", f"{name}.obj"), "w", newline="\n") as f:
        f.write(f"# generated by gazebo/worlds/build_nft46_assets.py\nmtllib {name}.mtl\no {name}\n")
        f.writelines(f"v {x:.5f} {y:.5f} {z:.5f}\n" for x, y, z in verts)
        f.writelines(f"vt {u:.4f} {v:.4f}\n" for u, v in uvs)
        f.writelines(f"vn {x:.4f} {y:.4f} {z:.4f}\n" for x, y, z in normals)
        f.write(f"usemtl {mtl}\n")
        for face in faces:
            f.write("f " + " ".join(f"{v + 1}/{t + 1}/{n + 1}" for v, t, n in face) + "\n")


def box_faces(sx, sy, sz, u_per_m=None):
    """A box centred at the origin with per-face UVs: u along each face's longest edge
    (u_per_m tiles per metre, else 0..1)."""
    hx, hy, hz = sx / 2, sy / 2, sz / 2
    faces_def = [  # normal, corners (counter-clockwise seen from outside), the face's (u, v) extents
        ((1, 0, 0), [(hx, -hy, -hz), (hx, hy, -hz), (hx, hy, hz), (hx, -hy, hz)], (sy, sz)),
        ((-1, 0, 0), [(-hx, hy, -hz), (-hx, -hy, -hz), (-hx, -hy, hz), (-hx, hy, hz)], (sy, sz)),
        ((0, 1, 0), [(hx, hy, -hz), (-hx, hy, -hz), (-hx, hy, hz), (hx, hy, hz)], (sx, sz)),
        ((0, -1, 0), [(-hx, -hy, -hz), (hx, -hy, -hz), (hx, -hy, hz), (-hx, -hy, hz)], (sx, sz)),
        ((0, 0, 1), [(-hx, -hy, hz), (hx, -hy, hz), (hx, hy, hz), (-hx, hy, hz)], (sx, sy)),
        ((0, 0, -1), [(-hx, hy, -hz), (hx, hy, -hz), (hx, -hy, -hz), (-hx, -hy, -hz)], (sx, sy)),
    ]
    V, T, N, F = [], [], [], []
    for n, corners, (eu, ev) in faces_def:
        long_first = eu >= ev
        lu, lv = (eu, ev) if long_first else (ev, eu)
        ku = lu * u_per_m if u_per_m else 1.0
        kv = lv * u_per_m if u_per_m else 1.0
        base_v, base_t = len(V), len(T)
        V.extend(corners)
        uv = [(0, 0), (1, 0), (1, 1), (0, 1)]
        if not long_first:
            uv = [(v, u) for u, v in uv]
        T.extend((u * ku, v * kv) for u, v in uv)
        N.append(n)
        ni = len(N) - 1
        F.append([(base_v + i, base_t + i, ni) for i in (0, 1, 2)])
        F.append([(base_v + i, base_t + i, ni) for i in (0, 2, 3)])
    return V, T, N, F


def tube_texture(path, size=128):
    """One inch of tube face: green paint, a dark round hole in the middle."""
    rng = np.random.default_rng(3)
    base = np.array([18, 92, 58], np.float32)
    img = base + rng.normal(0, 4, (size, size, 3))
    im = Image.fromarray(np.clip(img, 0, 255).astype(np.uint8))
    d = ImageDraw.Draw(im)
    r = int(size * 0.2)
    c = size // 2
    d.ellipse((c - r - 3, c - r - 3, c + r + 3, c + r + 3), fill=(14, 70, 44))      # pressed rim
    d.ellipse((c - r, c - r, c + r, c + r), fill=(8, 10, 9))
    im = im.filter(ImageFilter.GaussianBlur(0.7))
    im.save(path)


def floor_texture(path, size=512):
    """Light grey vinyl with darker and lighter speckles (the lab floor in the photos)."""
    rng = np.random.default_rng(5)
    img = np.full((size, size, 3), 196, np.float32) + rng.normal(0, 3, (size, size, 1))
    im = Image.fromarray(np.clip(img, 0, 255).astype(np.uint8))
    d = ImageDraw.Draw(im)
    for _ in range(2600):
        x, y = rng.integers(0, size, 2)
        r = rng.uniform(0.6, 2.2)
        g = int(rng.choice([90, 120, 150, 235, 250]))
        d.ellipse((x - r, y - r, x + r, y + r), fill=(g, g, g - 4))
    im.filter(ImageFilter.GaussianBlur(0.4)).save(path)


def tube_mesh(length):
    """mesh name of a TUBE x TUBE x length tube (along z), holes one inch apart."""
    name = f"tube_{int(round(length * 1000))}"
    V, T, N, F = box_faces(TUBE, TUBE, length, u_per_m=1.0 / HOLE_PITCH)
    write_obj(name, V, T, N, F, "green_steel", texture="tube.png", kd=(1, 1, 1), ks=0.25, ns=40)
    return name


def channel_mesh():
    """NFT channel along y, origin at the middle of its top surface (cover)."""
    w, h, L = CH_W, CH_H, CH_LEN
    lip, lip_w = 0.006, 0.006
    bot = w * 0.8
    # profile in (x, z), counter-clockwise from the bottom left
    prof = [(-bot / 2, -h), (bot / 2, -h), (w / 2, -0.004), (w / 2, lip), (w / 2 - lip_w, lip),
            (w / 2 - lip_w, 0.0), (-w / 2 + lip_w, 0.0), (-w / 2 + lip_w, lip), (-w / 2, lip), (-w / 2, -0.004)]
    V, T, N, F = [], [], [], []
    ys = (-L / 2, L / 2)
    n_p = len(prof)
    for i in range(n_p):  # one flat quad per profile edge
        (x0, z0), (x1, z1) = prof[i], prof[(i + 1) % n_p]
        nx, nz = (z1 - z0), -(x1 - x0)
        ln = math.hypot(nx, nz) or 1.0
        N.append((nx / ln, 0.0, nz / ln))
        ni = len(N) - 1
        b = len(V)
        V += [(x0, ys[0], z0), (x1, ys[0], z1), (x1, ys[1], z1), (x0, ys[1], z0)]
        T += [(0, 0), (1, 0), (1, 1), (0, 1)]
        # outward for a counter-clockwise profile: (v0, v3, v2), (v0, v2, v1)
        F.append([(b, b, ni), (b + 3, b + 3, ni), (b + 2, b + 2, ni)])
        F.append([(b, b, ni), (b + 2, b + 2, ni), (b + 1, b + 1, ni)])
    for end, y in ((-1, ys[0]), (1, ys[1])):  # end caps: fan from the centroid
        N.append((0.0, float(end), 0.0))
        ni = len(N) - 1
        cx = sum(p[0] for p in prof) / n_p
        cz = sum(p[1] for p in prof) / n_p
        c = len(V)
        V.append((cx, y, cz))
        T.append((0.5, 0.5))
        b = len(V)
        V += [(x, y, z) for x, z in prof]
        T += [(0.5, 0.5)] * n_p
        for i in range(n_p):
            a_, b_ = b + i, b + (i + 1) % n_p
            F.append([(c, c, ni), (a_, a_, ni), (b_, b_, ni)] if end < 0 else [(c, c, ni), (b_, b_, ni), (a_, a_, ni)])
    write_obj("channel", V, T, N, F, "pvc_white", kd=(0.95, 0.95, 0.94), ks=0.35, ns=60)


def floor_mesh(size=12.0, tile=0.6):
    h = size / 2
    k = size / tile
    V = [(-h, -h, 0), (h, -h, 0), (h, h, 0), (-h, h, 0)]
    T = [(0, 0), (k, 0), (k, k), (0, k)]
    write_obj("floor", V, T, [(0, 0, 1)], [[(0, 0, 0), (1, 1, 0), (2, 2, 0)], [(0, 0, 0), (2, 2, 0), (3, 3, 0)]],
              "vinyl", texture="floor.png", ks=0.15, ns=30)


def build():
    os.makedirs(os.path.join(OUT, "textures"), exist_ok=True)
    tube_texture(os.path.join(OUT, "textures", "tube.png"))
    floor_texture(os.path.join(OUT, "textures", "floor.png"))
    channel_mesh()
    floor_mesh()


if __name__ == "__main__":
    build()
    print(f"assets in {OUT}")

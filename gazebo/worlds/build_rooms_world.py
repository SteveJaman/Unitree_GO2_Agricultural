#!/usr/bin/env python3
"""
build_rooms_world.py: write agri_rooms.sdf = agri_field.sdf + a building.

The open field is mapped from the spawn point in one scan, so the frontier
explorer finishes after a few goals. This adds space the lidar cannot see
until the robot goes there: a building on the field's north side, entered
through a doorway in the field's north wall.

  y = 11.05  +-----------+-----------+-----------+
             |  room 1   |  room 2   |  room 3   |
             |  crates   | workbench D  alcove   |   D = door room 2 <-> 3
             |           |           |  ----     |
  y =  6.05  +--D--------+------D----+--------D--+
             |              corridor (2 m)       |
  y =  4.05  +--D--------------------------------+   field north wall
                ^ doorway from the field (x = -4)
             x = -6.05                   x = 6.05

The whole site spans 12 x 15 m, inside the 30 x 30 m rolling global costmap
around the robot wherever it stands, so mapped space is not forgotten and
re-explored. Doors are 1.2 m (the Go2 footprint is 0.81 x 0.40 m plus
padding); walls are 1.2 m tall so the lidar cannot see over them.

Usage: python3 build_rooms_world.py   (rewrites agri_rooms.sdf next to it)
Edit the layout constants below, then rerun.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "agri_field.sdf")
DST = os.path.join(HERE, "agri_rooms.sdf")

X0, X1 = -6.05, 6.05          # building west/east walls (same as the field)
Y_FIELD = 4.05                # field north wall = building south wall
Y_CORR = 6.05                 # corridor north wall
Y1 = 11.05                    # building north wall
ROOM_X = [-2.05, 2.05]        # partitions between rooms 1|2 and 2|3
DOOR = 1.2
WALL_H = 1.2
WALL_T = 0.1

# (wall, door centre) pairs; a wall is ("x" or "y", fixed coord, from, to)
FIELD_DOOR_X = -4.0
ROOM_DOORS_X = [-5.0, 1.0, 4.8]       # corridor -> room 1, 2, 3
ROOM23_DOOR_Y = 9.8                   # room 2 <-> room 3

WALL_RGB = "0.82 0.80 0.76"
CRATE_RGB = "0.55 0.40 0.22"
BENCH_RGB = "0.35 0.35 0.40"


def box_link(name, x, y, z, sx, sy, sz, rgb):
    return f"""      <link name="{name}">
        <pose>{x:.3f} {y:.3f} {z:.3f} 0 0 0</pose>
        <collision name="c"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry></collision>
        <visual name="v"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry>
          <material><ambient>{rgb} 1</ambient><diffuse>{rgb} 1</diffuse></material></visual>
      </link>
"""


def wall(name, axis, fixed, a, b, doors=()):
    """Wall from a to b along axis ("x": runs along x at y=fixed), with
    DOOR-wide gaps centred on each value in doors."""
    cuts = sorted((d - DOOR / 2, d + DOOR / 2) for d in doors)
    spans, start = [], a
    for c0, c1 in cuts:
        spans.append((start, c0))
        start = c1
    spans.append((start, b))
    out = []
    for i, (s, e) in enumerate(spans):
        if e - s < 0.05:
            continue
        mid, length = (s + e) / 2, e - s
        if axis == "x":
            out.append(box_link(f"{name}_{i}", mid, fixed, WALL_H / 2, length, WALL_T, WALL_H, WALL_RGB))
        else:
            out.append(box_link(f"{name}_{i}", fixed, mid, WALL_H / 2, WALL_T, length, WALL_H, WALL_RGB))
    return "".join(out)


def building():
    t = WALL_T / 2
    links = [
        wall("south", "x", Y_FIELD, X0 - t, X1 + t, [FIELD_DOOR_X]),
        wall("corridor", "x", Y_CORR, X0, X1, ROOM_DOORS_X),
        wall("north", "x", Y1, X0 - t, X1 + t),
        wall("west", "y", X0, Y_FIELD, Y1),
        wall("east", "y", X1, Y_FIELD, Y1),
        wall("part12", "y", ROOM_X[0], Y_CORR, Y1),
        wall("part23", "y", ROOM_X[1], Y_CORR, Y1, [ROOM23_DOOR_Y]),
        # Room 3: a wall off the east side makes an alcove behind it.
        wall("alcove", "x", 8.5, 3.6, X1),
        # Things to scan around.
        box_link("crate_a", -4.5, 9.6, 0.3, 0.6, 0.6, 0.6, CRATE_RGB),
        box_link("crate_b", -3.1, 8.0, 0.3, 0.6, 0.6, 0.6, CRATE_RGB),
        box_link("workbench", 0.0, 9.2, 0.4, 1.6, 0.8, 0.8, BENCH_RGB),
        box_link("planter", 2.6, 4.35, 0.25, 0.5, 0.5, 0.5, CRATE_RGB),
    ]
    return ('    <model name="building">\n      <static>true</static>\n'
            + "".join(links) + "    </model>\n")


def main():
    with open(SRC) as f:
        sdf = f.read()
    sdf = sdf.replace('<world name="agri_field">', '<world name="agri_rooms">', 1)
    # The building's south wall (with the doorway) replaces the field's north wall.
    sdf, n = re.subn(r'\s*<link name="north">.*?</link>', "", sdf, count=1, flags=re.S)
    if n != 1:
        raise SystemExit("agri_field.sdf: field north wall not found")
    sdf = re.sub(r"<!--.*?-->",
                 "<!--\n  agri_rooms.sdf: GENERATED by build_rooms_world.py from agri_field.sdf.\n"
                 "  Do not edit by hand; edit the script (or agri_field.sdf) and rerun it.\n"
                 "  The field plus a building to the north (corridor + 3 rooms) for\n"
                 "  frontier-exploration tests. @RENDER_ENGINE@ is substituted by\n"
                 "  start_inside.sh.\n-->", sdf, count=1, flags=re.S)
    sdf = sdf.replace("  </world>", building() + "  </world>", 1)
    with open(DST, "w") as f:
        f.write(sdf)
    print(f"wrote {DST}")


if __name__ == "__main__":
    main()
